import type { TauraReport } from "./api";

/** ok: traces to the ledger · stale: the ledger changed since publish · untracked: no provenance · warn: taura flags it */
export type Level = "ok" | "stale" | "untracked" | "warn";

export interface Marker {
  /** 1-based line. */
  line: number;
  level: Level;
  /** Short lines describing each thing on the line. */
  notes: string[];
  /** What `taura trace` takes for this line: a \res key or an artifact name. */
  targets: string[];
}

const RANK: Record<Level, number> = { ok: 0, warn: 1, stale: 2, untracked: 3 };

// Code-side findings that mean an artifact in the paper is out of date.
const STALE_IDS = new Set(["stale-artifact", "provenance-changed", "stale-source", "missing-source", "missing-result"]);

/**
 * Gutter markers for one file: each \res number, each figure and table, and each line taura
 * flags (typed numbers that match a result, undefined keys, figures without provenance).
 */
export function markersFor(file: string, text: string, report: TauraReport): Marker[] {
  const byLine = new Map<number, Marker>();
  const mark = (line: number, level: Level, note: string, target?: string) => {
    const m = byLine.get(line) ?? { line, level, notes: [], targets: [] };
    if (RANK[level] > RANK[m.level]) m.level = level;
    // Problems go first, so the popover leads with them.
    const add = (list: string[], item: string) => (level === "ok" ? list.push(item) : list.unshift(item));
    if (!m.notes.includes(note)) add(m.notes, note);
    if (target && !m.targets.includes(target)) add(m.targets, target);
    byLine.set(line, m);
  };

  const paperFindings = new Map<number, typeof report.findings>();
  for (const f of report.findings) {
    const match = f.repo === "paper" ? /^(.+):(\d+)$/.exec(f.location) : null;
    if (match && match[1] === file) {
      const line = Number(match[2]);
      paperFindings.set(line, [...(paperFindings.get(line) ?? []), f]);
    }
  }
  const staleArtifacts = new Set([
    ...report.findings.filter((f) => f.repo === "code" && STALE_IDS.has(f.id)).map((f) => f.location),
    ...report.changes.filter((c) => !c.what.startsWith("\\res{")).map((c) => c.artifact),
  ]);
  const changedKeys = new Map(
    report.changes.filter((c) => c.what.startsWith("\\res{")).map((c) => [c.what.slice(5, -1), c] as const),
  );
  const artifactFor = (path: string) => {
    const clean = path.replace(/^\.\//, "");
    return report.artifacts.find((a) => a.output === clean || a.output.replace(/\.[^./]+$/, "") === clean);
  };

  const lines = text.split("\n");
  let tableStart = 0;
  let tableHasArtifact = false;
  lines.forEach((raw, i) => {
    const n = i + 1;
    const line = stripComment(raw);

    for (const m of line.matchAll(/\\res\{([^}]+)\}/g)) {
      const key = m[1];
      const change = changedKeys.get(key);
      if (paperFindings.get(n)?.some((f) => f.id === "dangling-key" && f.message.includes(key))) continue;
      if (change) mark(n, "stale", `\\res{${key}}: publishing would change ${change.old ?? "?"} → ${change.new ?? "?"}`, key);
      else mark(n, "ok", `\\res{${key}} traces to the ledger`, key);
    }

    for (const m of line.matchAll(/\\(includegraphics|input|include)\s*(?:\[[^\]]*\])?\{([^}]+)\}/g)) {
      const [, command, path] = m;
      const artifact = artifactFor(path);
      if (artifact) {
        tableHasArtifact = true;
        if (staleArtifacts.has(artifact.name)) mark(n, "stale", `${artifact.name}: changed in the code repo since it was published`, artifact.name);
        else mark(n, "ok", `${artifact.name} (${artifact.kind}) traces to the ledger`, artifact.name);
      } else if (command === "includegraphics") {
        mark(n, "untracked", `${path}: figure has no provenance (not generated by taura)`);
      }
    }

    if (/\\begin\{table\*?\}/.test(line)) {
      tableStart = n;
      tableHasArtifact = false;
    }
    if (tableStart && /\\end\{table\*?\}/.test(line)) {
      if (!tableHasArtifact) mark(tableStart, "untracked", "Table typed by hand: no taura artifact behind it");
      tableStart = 0;
    }

    for (const f of paperFindings.get(n) ?? []) {
      const level: Level = ["dangling-key", "missing-figure", "untracked-figure"].includes(f.id) ? "untracked" : "warn";
      mark(n, level, `${f.message}. Fix: ${f.fix}`);
    }
  });
  return [...byLine.values()].sort((a, b) => a.line - b.line);
}

function stripComment(line: string): string {
  const i = line.search(/(?<!\\)%/);
  return i === -1 ? line : line.slice(0, i);
}

const el = <K extends keyof HTMLElementTagNameMap>(tag: K, className?: string, text?: string) => {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
};

const short = (commit: unknown) => (typeof commit === "string" ? commit.slice(0, 7) : "");
const day = (stamp: unknown) => (typeof stamp === "string" ? stamp.slice(0, 16).replace("T", " ") : "");

/** A compact summary of `taura trace` output: where a number or figure came from. */
export function renderTrace(trace: Record<string, any>): HTMLElement {
  const box = el("div", "trace");
  // trace lists a claim once per place it's used; show each key once with all its places.
  const items: any[] = [];
  const usedAt = new Map<string, string[]>();
  for (const item of trace.items ?? []) {
    if (item.kind === "claim" && usedAt.has(item.key)) {
      usedAt.get(item.key)!.push(item.location);
      continue;
    }
    if (item.kind === "claim") usedAt.set(item.key, [item.location]);
    items.push(item);
  }
  for (const item of items) {
    const rows: [string, string][] = [];
    if (item.kind === "claim") {
      box.append(el("div", "trace-title", `\\res{${item.key}} = ${item.printed ?? item.current ?? "?"}`));
      const r = item.result ?? {};
      rows.push(["Result", r.label ?? r.name ?? ""], ["Ledger", r.file ?? ""], ["Exported by", r.produced_by ?? ""]);
      rows.push(["Used at", (usedAt.get(item.key) ?? []).filter(Boolean).join(", ")]);
      if (item.current !== undefined && item.current !== item.printed) rows.push(["Ledger now", String(item.current)]);
      if (r.changed_since_publish) rows.push(["Status", "changed in the code repo since publish"]);
      addRuns(rows, r.run_records);
    } else if (item.kind === "artifact") {
      box.append(el("div", "trace-title", `${item.name} (${item.artifact_kind})`));
      rows.push(["Output", item.output ?? ""], ["Source", item.lock?.source ?? item.made?.source ?? ""], ["Script", item.lock?.script ?? item.made?.made_by ?? ""]);
      const changed = (item.inputs ?? []).filter((i: any) => i.changed_since_publish).map((i: any) => i.name);
      if (changed.length) rows.push(["Changed inputs", changed.join(", ")]);
      if (item.published === false) rows.push(["Status", "never published"]);
      addRuns(rows, item.run_records);
    } else {
      box.append(el("div", "trace-title", String(item.key ?? item.name ?? item.kind)));
    }
    const p = item.publish;
    if (p) rows.push(["Published", `${day(p.published)} from ${short(p.code_commit)} (${p.code_repo})`]);

    const table = el("dl", "trace-rows");
    for (const [k, v] of rows.filter(([, v]) => v)) table.append(el("dt", "", k), el("dd", "", v));
    box.append(table);
  }
  if (!box.childElementCount) box.append(el("p", "", "taura has nothing recorded for this."));
  return box;
}

function addRuns(rows: [string, string][], runs: any[] | undefined) {
  for (const run of (runs ?? []).slice(0, 2)) {
    const data = Object.values(run.data ?? {}).map((d: any) => d.label ?? d.path).join(", ");
    rows.push(["Run", `${run.command ?? ""} @ ${short(run.commit)}${run.dirty ? " (uncommitted changes)" : ""}`]);
    if (data) rows.push(["Data", data]);
  }
}
